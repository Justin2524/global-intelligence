import fs from 'node:fs';
import path from 'node:path';
import { parseIssue, serializeReport, readReport, check } from './content.mjs';
export function ingest(event, root, repository) {
  const report = parseIssue(event, repository);
  const slug = `${report.date}-${report.type}`;
  const relative = `reports/${slug}.md`;
  const dir = path.join(root, 'reports');
  fs.mkdirSync(dir, { recursive: true });
  check(!fs.lstatSync(dir).isSymbolicLink(), '报告目录不能是符号链接。');
  const file = path.join(root, relative);
  let status = 'created';
  if (fs.existsSync(file)) {
    check(!fs.lstatSync(file).isSymbolicLink(), '目标文件不能是符号链接。');
    const old = readReport(fs.readFileSync(file, 'utf8'));
    check(old.issue === report.issue && old.body_sha256 === report.body_sha256, '同日同类型文章已存在，拒绝覆盖。若原工作流发布失败，请重跑原工作流。');
    status = 'retry';
  } else fs.writeFileSync(file, serializeReport(report), { flag: 'wx' });
  return { path: relative, slug, status, issue: report.issue, body_sha256: report.body_sha256 };
}
if (process.argv[1] === new URL(import.meta.url).pathname) {
  try {
    const event = JSON.parse(fs.readFileSync(process.env.GITHUB_EVENT_PATH, 'utf8'));
    const result = ingest(event, process.cwd(), process.env.GITHUB_REPOSITORY);
    if (process.env.GITHUB_OUTPUT) fs.appendFileSync(process.env.GITHUB_OUTPUT, Object.entries(result).map(([k,v]) => `${k}=${v}\n`).join(''));
    console.log(JSON.stringify(result));
  } catch (error) {
    // Error strings are generated by our validator, never treated as shell or workflow commands.
    fs.mkdirSync('artifacts', { recursive: true });
    fs.writeFileSync('artifacts/validation-error.txt', error.message);
    console.error(`验证失败：${error.message}`); process.exitCode = 1;
  }
}
